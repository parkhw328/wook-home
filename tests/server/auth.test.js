import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, existsSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createAuth } from '../../server/auth.js';
import { createStore } from '../../server/store.js';
import { createOffice } from '../../server/office.js';
import { createHttpServer } from '../../server/http.js';

test('admin login gates APIs, changes bootstrap password, expires and invalidates sessions', async (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'office-auth-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  let time = Date.now();
  const auth = await createAuth(dir, { clock: () => time });
  const initial = readFileSync(join(dir, 'admin-initial-password.txt'), 'utf8').trim().split('\n')[1];
  assert.equal(statSync(join(dir, 'admin-auth.json')).mode & 0o777, 0o600);
  assert.ok(!readFileSync(join(dir, 'admin-auth.json'), 'utf8').includes(initial));
  const store = createStore(':memory:');
  const server = createHttpServer(createOffice(store), { auth });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise((resolve) => server.close(resolve)); store.close(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  let cookie = '';
  const call = (path, body, headers = {}) => fetch(`${base}${path}`, { redirect: 'manual', method: body ? 'POST' : 'GET', headers: { Cookie: cookie, 'Content-Type': 'application/json', ...headers }, ...(body ? { body: JSON.stringify(body) } : {}) });
  for (const path of ['/api/state', '/api/handoff', '/api/search/status', '/api/discovery', '/api/bridge/settings', '/api/history/query']) assert.equal((await call(path)).status, 401);
  assert.equal((await call('/')).headers.get('location'), '/login.html');
  assert.equal((await call('/api/auth/login', { username: 'admin', password: initial }, { Origin: 'https://wrong.invalid' })).status, 403);
  assert.equal((await call('/api/auth/login', { username: 'admin', password: 'incorrect' })).status, 401);
  const login = await call('/api/auth/login', { username: 'admin', password: initial });
  assert.equal(login.status, 200);
  assert.match(login.headers.get('set-cookie'), /HttpOnly; SameSite=Strict/);
  cookie = login.headers.get('set-cookie').split(';')[0];
  assert.equal((await call('/api/state')).status, 403);
  assert.equal((await call('/api/auth/password', { currentPassword: initial, newPassword: 'short' })).status, 400);
  const password = 'test-only-new-password-739!';
  const changed = await call('/api/auth/password', { currentPassword: initial, newPassword: password });
  assert.equal(changed.status, 200);
  assert.equal((await call('/api/state')).status, 401);
  cookie = changed.headers.get('set-cookie').split(';')[0];
  assert.equal((await call('/api/state')).status, 200);
  assert.equal(existsSync(join(dir, 'admin-initial-password.txt')), false);
  const restarted = await createAuth(dir);
  assert.equal(restarted.user({ headers: { cookie } }), null);
  assert.equal((await restarted.login({ headers: {}, socket: {} }, { username: 'admin', password })).user.mustChangePassword, false);
  time += 8 * 3600000;
  assert.equal((await call('/api/state')).status, 401);
  const again = await call('/api/auth/login', { username: 'admin', password });
  cookie = again.headers.get('set-cookie').split(';')[0];
  await call('/api/auth/logout', {});
  assert.equal((await call('/api/state')).status, 401);
  for (let n = 0; n < 10; n++) assert.equal((await call('/api/auth/login', { username: 'admin', password: 'incorrect' })).status, 401);
  assert.equal((await call('/api/auth/login', { username: 'admin', password })).status, 429);
});
